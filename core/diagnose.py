    "AUTH_INVALID",         # 这家 key 不对
    "ACCOUNT_BANNED",       # 这家账号/线路不可用
    "MODEL_NOT_FOUND",      # 这家没这个模型
    "RATE_LIMITED",         # 这家在限流，换一家能继续
    "NETWORK",              # 这家连不上
