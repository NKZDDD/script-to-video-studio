def limits_note(limits: Optional[dict]) -> str:
    if not limits:
        return ("（当前没配出图/出片服务商，所以给不出具体数字 —— "
                "配好之后重新导出这份契约，这里会写上真实上限）")
    bits = [f"{'出图' if k == 'image' else '出片'}一次最多 {v} 张"
            for k, v in sorted(limits.items())]
    return "**本项目当前的上限：" + "；".join(bits) + "**（按你配的首选那一家算的）"


def jsonl_schema() -> str:
    """推荐格式：一行一条 JSON。

    这份样例是**一份完全合格的最小材料** —— 抄下来原样导入会 0 条问题。
    所以它同时是文档和自检：引用链闭合、编号连续、申报和实物对得上，
    三样都在这四行里演示了。示例自己不合格的话，照它产出来的也不会合格。
    """
    man = {
        "kind": "manifest",
        "total": 3, "image": 2, "video": 1,
        "episodes": 1, "segs_per_episode": {"EP01": 1},
    }
    sb = {
        "kind": "image",
        "key": "PRJ_X__SBSHEET_EP01_SEG01_A_R01",
        "family": "SBSHEET",
        "name": "EP01-SEG01 故事板 A",
        "filename": "PRJ_X__SBSHEET_EP01_SEG01_A_R01.png",
        "size": "9:16",
        "reference_images": [],
        "prompt": "（完整可投喂提示词正文，一个字都不要省）",
    }
    img = {
        "kind": "image",
        "key": "PRJ_X__CHAR_001_R02",
        "family": "CHAR",
        "name": "林溪身份根",
        "filename": "PRJ_X__CHAR_001_R02.png",
        "size": "9:16",
        "reference_images": [],
        "prompt": "（完整可投喂提示词正文，一个字都不要省）",
    }
    vid = {
        "kind": "video",
        "key": "EP01-SEG01",
        "episode": "EP01",
        "seg": "SEG01",
        "filename": "PRJ_X__VIDEO_EP01_SEG01_R01.mp4",
        "duration": 15,
        "ratio": "9:16",
        "storyboard_refs": [
            {"image_n": 1, "key": "PRJ_X__SBSHEET_EP01_SEG01_A_R01",
             "role": "ENTRY"}],
        "reference_images": [
            {"image_n": 2, "key": "PRJ_X__CHAR_001_R02",
             "who": "19岁林溪；校服脏湿、掌心烧伤",
             "controls": "身份与当前 LOOK/CT",
             "not_controls": "节奏、镜头顺序、站位",
             "scope": "仅在该人物出现的时间窗"}],
        "prompt": "（完整可投喂提示词正文）",
    }
    import json as _j
    return chr(10).join(_j.dumps(r, ensure_ascii=False)
                        for r in (man, sb, img, vid))


def render(limits: Optional[dict] = None, project_name: str = "") -> str:
    """生成契约正文（md）。"""
    L = []
    a = L.append
    a("# 生产材料契约"
      + (f"｜{project_name}" if project_name else ""))
    a("")
    a("这份是**程序要吃的结构**，从代码现算出来的（`core/matspec.py`）——"
      "所以它和实际要求永远是同一份东西，不会飘。")
    a("")
    a("## 一句话")
    a("")
    a("你产出的每一条 = **一个可以直接投喂的生产任务**。"
      "程序不再做任何 LLM 环节，拿到你的材料就直接出图出片。")
    a("")
    a("## 格式：一行一条 JSON（JSONL）")
    a("")
    a("**别用 md 散文。** 散文要靠猜排版：全角等号还是半角、"
      "`Image N` 在参考图那一节还是正文里复述、`---` 是分隔线还是内容 ——"
      "每一处猜错都是静默的（比如张数数成两倍，然后「超上限」全员误报）。"
      "JSONL 没有这些歧义，错在哪一行、哪个字段都能指出来。")
    a("")
    a("```jsonl")
    a(jsonl_schema())
    a("```")
    a("")
    a("## 第一行：申报头（必须有）")
    a("")
    a("材料第一行是一条 `{\"kind\": \"manifest\", ...}`，"
      "写清这一份里有几条、图片和视频各几条、共几集、每集几段。")
    a("")
    a("**这是唯一能查出「少产了」的东西。** 没有它的话，该 84 条只给 80 条时，"
      "剩下那 80 条引用链闭合、编号连续、段号连续 —— 全绿，"
      "程序一句话说不出来，直到成片短一截。")
    a("")
    a("边界也说清：对账查的是「你有没有兑现你自己说的」。"
      "申报 84、实际 84、但本该 88 —— 这个查不出来，那是你自己的判断，"
      "程序无从知道。")
    a("")
    a("## 字段：每一类各要什么")
    a("")
    for kind, rows in NEEDS.items():
        a(f"### {'图片' if kind == 'image' else '视频'}")
        a("")
        for f, why in rows:
            a(f"- `{f}` —— {why}")
        a("")
    a("## 参考图怎么写")
    a("")
    a("`image_n` **就是实际上传顺序**：第 1 个元素就是 Image 1。"
      "视频的骨架排在前面（`storyboard_refs`），补图接着排（`reference_images`）。")
    a("")
    a("提示词正文里**也要逐张写一遍身份映射**：")
    a("")
    a("```")
    a("Image 1 = <key> <名称>")
    a("  是谁/是什么 + 画面可见内容：…")
    a("  故事时间 / 当前状态：…")
    a("  有权控制：…")
    a("  无权控制：…")
    a("  适用范围：…")
    a("```")
    a("")
    a("出图前有**两道**检查：第一道查编号和上传顺序对不对，"
      "第二道查每个编号后面有没有说清这张图是谁。"
      "只写编号会被第二道拦下 ——「只说这张图控制服饰」不够，"
      "它不知道是哪个人，多人场景必然张冠李戴。")
    a("")
    a("## 落点（和程序自己跑 LLM 时完全一致）")
    a("")
    for what, where in DIRS.items():
        a(f"- **{what}** → `{where}`")
    a("")
    a("你只要给 `filename`，落哪个目录由程序按 key 里的家族算。")
    a("")
    a("## 会被怎么验收")
    a("")
    a("导入前会跑这几条，**有一条不过就不导** ——"
      "导进去之后它们已经变成任务了，那时候改要连带清任务。")
    a("")
    for name, why in AUDIT:
        a(f"- **{name}** —— {why}")
    a("")
    a(limits_note(limits))
    a("")
    a("## 不需要的东西")
    a("")
    a("程序原来那 27 个环节的中间产物（`n1_truth.json`、`n9_shots.json`、"
      "`n10_segs.json` 之类）**一份都不用给**。它们是「程序一步步问模型」"
      "时的中间结果；你一次想完整部剧，那些中间形态不存在。")
    a("")
    a("## 程序查不了的，靠你保证")
    a("")
    a("这几件**没有任何一处会说话**，出错要到看图看片才发现：")
    a("")
    a("- **提示词正文必须完整可投喂。** 不要写「同上」「同前」「略」「待补」，"
      "不要为了省篇幅截断。残篇会一路跑到出图那一刻 —— 图也出得来，只是不对。"
      "（用长度或占位词去猜都抓不准，所以程序不做这个检查。）")
    a("- **参考图要引对的那一个。** 引用链闭合只证明「这个 key 有人产出」，"
      "不证明「这一段该引它」。EP05 的场景引了 EP12 的房间，验收全绿。")
    a("- **时间连不连得上、总时长对不对。** 原来靠中间产物查的那几道"
      "（时间线跳秒、装箱漏镜头）在这条路上不存在。")
    a("")
    a("代价要说清：靠那些字段的几道闸门（时间线跳秒、装箱漏镜头、"
      "判定打架、集数对账）**查不了了**。所以上面「会被怎么验收」那几条"
      "是这条路上全部的检查 —— 剩下的靠你自己保证。")
    return "\n".join(L) + "\n"
